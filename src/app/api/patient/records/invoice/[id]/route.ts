/**
 * INVOICE PDF GENERATION
 * GET /api/patient/records/invoice/[id]/pdf — generates a printable invoice PDF
 * Requires hms_patient_session cookie (patient-scoped)
 */

import { NextRequest } from 'next/server'
import { PDFDocument, rgb, StandardFonts } from 'pdf-lib'
import { dbUnscoped } from '@/lib/db'

function getPatientId(req: NextRequest): string | null {
  const token = req.cookies.get('hms_patient_session')?.value
  if (!token) return null
  try {
    const payload = JSON.parse(Buffer.from(token, 'base64').toString('utf8'))
    return payload.kind === 'patient' ? payload.patientId : null
  } catch {
    return null
  }
}

export async function GET(
  req: NextRequest,
  { params }: { params: Promise<{ id: string }> }
) {
  const { id } = await params
  const patientId = getPatientId(req)
  if (!patientId) {
    return new Response(JSON.stringify({ error: 'Unauthorized' }), {
      status: 401,
      headers: { 'Content-Type': 'application/json' },
    })
  }

  const invoice = await dbUnscoped.invoice.findUnique({
    where: { id },
    include: { patient: true },
  })

  if (!invoice || invoice.patientId !== patientId) {
    return new Response(JSON.stringify({ error: 'Invoice not found.' }), {
      status: 404,
      headers: { 'Content-Type': 'application/json' },
    })
  }

  const pdfDoc = await PDFDocument.create()
  const page = pdfDoc.addPage([612, 792])
  const font = await pdfDoc.embedFont(StandardFonts.Helvetica)
  const boldFont = await pdfDoc.embedFont(StandardFonts.HelveticaBold)

  const margin = 50
  const pageWidth = 612
  let y = 792 - margin

  // Header
  page.drawText('INVOICE', {
    x: margin,
    y,
    size: 24,
    font: boldFont,
    color: rgb(0.13, 0.58, 0.55),
  })
  y -= 40

  page.drawText(`Invoice No: ${invoice.invoiceNo}`, {
    x: margin,
    y,
    size: 12,
    font: boldFont,
  })
  page.drawText(
    `Date: ${new Date(invoice.createdAt).toLocaleDateString('en-IN')}`,
    { x: margin + 300, y, size: 12, font }
  )
  y -= 30

  page.drawText(
    `Patient: ${invoice.patient.name} (UHID: ${invoice.patient.uhid})`,
    { x: margin, y, size: 12, font }
  )
  y -= 20

  page.drawText(`Bill Type: ${invoice.billType}`, { x: margin, y, size: 12, font })
  y -= 40

  page.drawText('Description', { x: margin, y, size: 12, font: boldFont })
  page.drawText('Amount', {
    x: pageWidth - margin - 80,
    y,
    size: 12,
    font: boldFont,
  })
  y -= 20

  const amount = invoice.totalAmount || 0
  page.drawText(invoice.billType || 'Service', { x: margin, y, size: 12, font })
  page.drawText(`₹${amount.toLocaleString('en-IN')}`, {
    x: pageWidth - margin - 80,
    y,
    size: 12,
    font,
  })
  y -= 40

  page.drawText('Total', {
    x: pageWidth - margin - 120,
    y,
    size: 14,
    font: boldFont,
  })
  page.drawText(`₹${amount.toLocaleString('en-IN')}`, {
    x: pageWidth - margin - 80,
    y,
    size: 14,
    font: boldFont,
  })
  y -= 60

  page.drawText(
    'Generated by AetherMed Cloud HMS · Patient Portal',
    { x: margin, y, size: 9, font, color: rgb(0.5, 0.5, 0.5) }
  )

  const pdfBytes = await pdfDoc.save()

  return new Response(Buffer.from(pdfBytes), {
    status: 200,
    headers: {
      'Content-Type': 'application/pdf',
      'Content-Disposition': `attachment; filename="invoice-${invoice.invoiceNo}.pdf"`,
    },
  })
}
