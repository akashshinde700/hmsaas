/**
 * DISCHARGE SUMMARY PDF GENERATION
 * GET /api/ipd/admissions/[id]/discharge-pdf — generates a printable discharge summary PDF
 * Requires hms_patient_session cookie (patient-scoped) or tenant session
 */

import { NextRequest } from 'next/server'
import { PDFDocument, rgb, StandardFonts } from 'pdf-lib'
import { dbUnscoped } from '@/lib/db'
import { verifyActiveTenantSession } from '@/lib/auth'

function getPatientIdFromPatientCookie(req: NextRequest): string | null {
  const token = req.cookies.get('hms_patient_session')?.value
  if (!token) return null
  try {
    const payload = JSON.parse(Buffer.from(token, 'base64').toString('utf8'))
    return payload.kind === 'patient' ? payload.patientId : null
  } catch {
    return null
  }
}

export async function GET(
  req: NextRequest,
  { params }: { params: Promise<{ id: string }> }
) {
  const { id } = await params

  // Allow either patient (own record) or tenant staff
  const patientId = getPatientIdFromPatientCookie(req)
  const session = await verifyActiveTenantSession(req)

  if (!patientId && !session) {
    return new Response(JSON.stringify({ error: 'Unauthorized' }), {
      status: 401,
      headers: { 'Content-Type': 'application/json' },
    })
  }

  const admission = await dbUnscoped.ipdAdmission.findUnique({
    where: { id },
    include: {
      patient: true,
      bed: { include: { category: true } },
      admittingDoctor: { select: { name: true, specialization: true, registrationNo: true } },
    },
  })

  if (!admission) {
    return new Response(JSON.stringify({ error: 'Admission not found.' }), {
      status: 404,
      headers: { 'Content-Type': 'application/json' },
    })
  }

  // Patient can only access their own admission
  if (patientId && admission.patientId !== patientId) {
    return new Response(JSON.stringify({ error: 'Forbidden' }), {
      status: 403,
      headers: { 'Content-Type': 'application/json' },
    })
  }

  // Tenant staff can only access their own org
  if (session && admission.organizationId !== session.organizationId && session.role !== 'super_admin') {
    return new Response(JSON.stringify({ error: 'Forbidden' }), {
      status: 403,
      headers: { 'Content-Type': 'application/json' },
    })
  }

  const pdfDoc = await PDFDocument.create()
  const page = pdfDoc.addPage([612, 792])
  const font = await pdfDoc.embedFont(StandardFonts.Helvetica)
  const boldFont = await pdfDoc.embedFont(StandardFonts.HelveticaBold)

  const margin = 50
  const pageWidth = 612
  let y = 792 - margin

  // Header
  page.drawText('DISCHARGE SUMMARY', {
    x: margin,
    y,
    size: 22,
    font: boldFont,
    color: rgb(0.13, 0.58, 0.55),
  })
  y -= 30

  page.drawText(`Admission No: ${admission.admissionNo}`, { x: margin, y, size: 12, font: boldFont })
  y -= 20

  page.drawText(`Patient: ${admission.patient.name} (UHID: ${admission.patient.uhid})`, {
    x: margin,
    y,
    size: 12,
    font,
  })
  y -= 15

  page.drawText(`Age/Gender: ${admission.patient.ageYears || 'N/A'}Y / ${admission.patient.gender}`, {
    x: margin,
    y,
    size: 12,
    font,
  })
  y -= 15

  page.drawText(`Bed: ${admission.bed.bedNumber} (${admission.bed.category.name})`, {
    x: margin,
    y,
    size: 12,
    font,
  })
  y -= 15

  page.drawText(`Admitting Doctor: Dr. ${admission.admittingDoctor.name}`, {
    x: margin,
    y,
    size: 12,
    font,
  })
  y -= 30

  // Sections
  const section = (title: string, content: string | null | undefined) => {
    page.drawText(title, { x: margin, y, size: 12, font: boldFont })
    y -= 15
    page.drawText(content || 'Not recorded', { x: margin, y, size: 11, font })
    y -= 25
  }

  section('Provisional Diagnosis', admission.provisionalDiagnosis)
  section('Final Diagnosis', admission.finalDiagnosis)
  section('Condition at Discharge', admission.conditionAtDischarge)
  section('Discharge Summary', admission.dischargeSummary)
  section('Discharge Advice', admission.dischargeAdvice)

  if (admission.dischargedAt) {
    page.drawText(`Discharged At: ${new Date(admission.dischargedAt).toLocaleString('en-IN')}`, {
      x: margin,
      y,
      size: 12,
      font,
    })
  }

  page.drawText(
    'Generated by AetherMed Cloud HMS · This document is confidential.',
    { x: margin, y: 60, size: 9, font, color: rgb(0.5, 0.5, 0.5) }
  )

  const pdfBytes = await pdfDoc.save()

  return new Response(Buffer.from(pdfBytes), {
    status: 200,
    headers: {
      'Content-Type': 'application/pdf',
      'Content-Disposition': `attachment; filename="discharge-summary-${admission.admissionNo}.pdf"`,
    },
  })
}
